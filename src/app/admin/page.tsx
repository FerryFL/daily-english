import { Suspense } from "react";
import Link from "next/link";
import { redirect } from "next/navigation";
import { desc } from "drizzle-orm";
import { ArrowLeft, Shield } from "lucide-react";
import { getDb, isDbConfigured } from "@/db";
import { videos } from "@/db/schema";
import { isAdminEmail } from "@/lib/demo";
import { requireUser } from "@/lib/supabase/server";
import { getActiveDemoVideo } from "@/lib/video-service";
import { AdminDemoPicker } from "@/components/admin-demo-picker";
import { Navbar } from "@/components/navbar";
import { Button } from "@/components/ui/button";
import { Skeleton } from "@/components/ui/skeleton";

function AdminSkeleton() {
  return (
    <div className="mx-auto w-full max-w-5xl space-y-6 px-4 py-10 sm:px-6">
      <Skeleton className="h-9 w-56" />
      <div className="grid gap-5 sm:grid-cols-2 lg:grid-cols-3">
        <Skeleton className="h-64 rounded-2xl" />
        <Skeleton className="h-64 rounded-2xl" />
        <Skeleton className="h-64 rounded-2xl" />
      </div>
    </div>
  );
}

async function AdminContent() {
  const user = await requireUser();
  if (!isAdminEmail(user.email)) {
    redirect("/");
  }

  const activeDemo = await getActiveDemoVideo();

  const allVideos = isDbConfigured()
    ? await getDb()
        .select({
          id: videos.id,
          title: videos.title,
          channel: videos.channel,
          durationSec: videos.durationSec,
          isAutoGenerated: videos.isAutoGenerated,
        })
        .from(videos)
        .orderBy(desc(videos.fetchedAt))
    : [];

  return (
    <div className="flex min-h-svh flex-col">
      <Navbar
        user={{
          email: user.email,
          name: user.user_metadata?.full_name as string | undefined,
        }}
      />

      <main className="mx-auto w-full max-w-5xl flex-1 space-y-8 px-4 py-8 sm:px-6">
        <div className="flex flex-wrap items-center justify-between gap-4">
          <div className="space-y-1">
            <div className="flex items-center gap-2 text-xs font-semibold tracking-wider text-[#10B981] uppercase dark:text-[#34D399]">
              <Shield className="size-3.5" />
              Admin Panel
            </div>
            <h1 className="text-2xl font-bold tracking-tight sm:text-3xl">Manage Demo Video</h1>
            <p className="text-sm text-muted-foreground">
              Choose which uploaded video appears on the public homepage for guests to try.
            </p>
          </div>

          <Button asChild variant="outline" className="rounded-md">
            <Link href="/">
              <ArrowLeft className="size-4" />
              Back to Dashboard
            </Link>
          </Button>
        </div>

        <AdminDemoPicker videos={allVideos} initialDemoId={activeDemo.id} />
      </main>
    </div>
  );
}

export default function AdminPage() {
  return (
    <Suspense fallback={<AdminSkeleton />}>
      <AdminContent />
    </Suspense>
  );
}
