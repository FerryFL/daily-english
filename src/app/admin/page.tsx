import { Suspense } from "react";
import Link from "next/link";
import { redirect } from "next/navigation";
import { and, desc, eq, isNotNull } from "drizzle-orm";
import { authUsers } from "drizzle-orm/supabase";
import { ArrowLeft, Shield } from "lucide-react";
import { getDb, isDbConfigured } from "@/db";
import { progress, videos } from "@/db/schema";
import { isAdminEmail } from "@/lib/demo";
import { requireUser } from "@/lib/supabase/server";
import { getActiveDemoVideo } from "@/lib/video-service";
import { AdminDemoPicker, type AdminClipOption } from "@/components/admin-demo-picker";
import { Navbar } from "@/components/navbar";
import { Button } from "@/components/ui/button";
import { Skeleton } from "@/components/ui/skeleton";

function AdminSkeleton() {
  return (
    <div className="mx-auto w-full max-w-5xl space-y-6 px-4 py-10 sm:px-6">
      <Skeleton className="h-9 w-56" />
      <div className="grid gap-5 sm:grid-cols-2 lg:grid-cols-3">
        <Skeleton className="h-64 rounded-2xl" />
        <Skeleton className="h-64 rounded-2xl" />
        <Skeleton className="h-64 rounded-2xl" />
      </div>
    </div>
  );
}

async function AdminContent() {
  const user = await requireUser();
  if (!isAdminEmail(user.email)) {
    redirect("/");
  }

  const activeDemo = await getActiveDemoVideo();

  const [videoRows, clipRows] = isDbConfigured()
    ? await Promise.all([
        getDb()
          .select({
            id: videos.id,
            title: videos.title,
            channel: videos.channel,
            durationSec: videos.durationSec,
            isAutoGenerated: videos.isAutoGenerated,
          })
          .from(videos)
          .orderBy(desc(videos.fetchedAt)),
        getDb()
          .select({
            videoId: progress.videoId,
            userId: progress.userId,
            userEmail: authUsers.email,
            clipStartSec: progress.clipStartSec,
            clipEndSec: progress.clipEndSec,
          })
          .from(progress)
          .leftJoin(authUsers, eq(progress.userId, authUsers.id))
          .where(and(isNotNull(progress.clipStartSec), isNotNull(progress.clipEndSec)))
          .orderBy(desc(progress.updatedAt)),
      ])
    : [[], []];

  const clipsByVideo = new Map<string, AdminClipOption[]>();
  for (const row of clipRows) {
    if (row.clipStartSec === null || row.clipEndSec === null) continue;
    const isOwn = row.userId === user.id;
    const option: AdminClipOption = {
      key: `${row.userId}:${row.clipStartSec}-${row.clipEndSec}`,
      label: isOwn ? "Your clip" : row.userEmail ?? "Other user",
      isOwn,
      startSec: row.clipStartSec,
      endSec: row.clipEndSec,
    };
    const list = clipsByVideo.get(row.videoId) ?? [];
    list.push(option);
    clipsByVideo.set(row.videoId, list);
  }

  // Sort each video's clips so the admin's own clip appears first.
  const allVideos = videoRows.map((v) => {
    const clips = (clipsByVideo.get(v.id) ?? []).sort((a, b) => Number(b.isOwn) - Number(a.isOwn));
    return { ...v, clips };
  });

  const initialDemoClip =
    activeDemo.clipStartSec !== null && activeDemo.clipEndSec !== null
      ? { startSec: activeDemo.clipStartSec, endSec: activeDemo.clipEndSec }
      : null;

  return (
    <div className="flex min-h-svh flex-col">
      <Navbar
        user={{
          email: user.email,
          name: user.user_metadata?.full_name as string | undefined,
        }}
      />

      <main className="mx-auto w-full max-w-5xl flex-1 space-y-8 px-4 py-8 sm:px-6">
        <div className="flex flex-wrap items-center justify-between gap-4">
          <div className="space-y-1">
            <div className="flex items-center gap-2 text-xs font-semibold tracking-wider text-[#10B981] uppercase dark:text-[#34D399]">
              <Shield className="size-3.5" />
              Admin Panel
            </div>
            <h1 className="text-2xl font-bold tracking-tight sm:text-3xl">Manage Demo Video</h1>
            <p className="text-sm text-muted-foreground">
              Choose which uploaded video appears on the public homepage for guests to try.
            </p>
          </div>

          <Button asChild variant="outline" className="rounded-md">
            <Link href="/">
              <ArrowLeft className="size-4" />
              Back to Dashboard
            </Link>
          </Button>
        </div>

        <AdminDemoPicker
          videos={allVideos}
          initialDemoId={activeDemo.id}
          initialDemoClip={initialDemoClip}
        />
      </main>
    </div>
  );
}

export default function AdminPage() {
  return (
    <Suspense fallback={<AdminSkeleton />}>
      <AdminContent />
    </Suspense>
  );
}
