import { revalidatePath } from "next/cache";
import { NextResponse, type NextRequest } from "next/server";
import { buildChunks } from "@/lib/chunker";
import { needsCrop } from "@/lib/clip";
import { createClient } from "@/lib/supabase/server";
import { parseVideoId } from "@/lib/youtube";
import { ensureInitialProgress, getOrFetchVideo } from "@/lib/video-service";
import { TranscriptError } from "@/lib/transcript";

export async function GET(request: NextRequest) {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();

  if (!user) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  const raw = request.nextUrl.searchParams.get("v") ?? "";
  const videoId = parseVideoId(raw);
  if (!videoId) {
    return NextResponse.json(
      { error: "Invalid YouTube URL or video ID." },
      { status: 400 },
    );
  }

  try {
    const video = await getOrFetchVideo(videoId);
    const inferredDuration =
      video.durationSec ??
      (video.segments.length > 0
        ? Math.ceil(
            Math.max(...video.segments.map((s) => s.start + s.dur)),
          )
        : null);

    if (needsCrop(inferredDuration)) {
      return NextResponse.json({
        videoId: video.id,
        title: video.title,
        channel: video.channel,
        durationSec: inferredDuration,
        isAutoGenerated: video.isAutoGenerated,
        needsCrop: true,
      });
    }

    const chunks = buildChunks(video.segments);
    if (chunks.length > 0) {
      await ensureInitialProgress(user.id, video.id, chunks.length);
      revalidatePath("/");
    }
    return NextResponse.json({
      videoId: video.id,
      title: video.title,
      channel: video.channel,
      durationSec: inferredDuration,
      isAutoGenerated: video.isAutoGenerated,
      needsCrop: false,
      segments: video.segments,
    });
  } catch (err) {
    if (err instanceof TranscriptError) {
      return NextResponse.json({ error: err.message }, { status: err.status });
    }
    console.error("[api/transcript] unexpected error", err);
    return NextResponse.json(
      { error: "Failed to fetch captions. Please try again." },
      { status: 500 },
    );
  }
}
