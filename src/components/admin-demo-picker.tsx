"use client";

import { useState, useTransition } from "react";
import Link from "next/link";
import { CheckCircle2, Loader2, Play, Scissors, Sparkles } from "lucide-react";
import { toast } from "sonner";
import { setDemoVideo, type DemoClipRange } from "@/app/admin/actions";
import { formatTimestamp, needsCrop } from "@/lib/clip";
import { thumbnailUrl } from "@/lib/youtube";
import { cn } from "@/lib/utils";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";

export interface AdminClipOption {
  key: string;
  label: string;
  isOwn: boolean;
  startSec: number;
  endSec: number;
}

export interface AdminVideoItem {
  id: string;
  title: string;
  channel: string | null;
  durationSec: number | null;
  isAutoGenerated: boolean;
  clips: AdminClipOption[];
}

function formatDuration(sec: number | null): string | null {
  if (!sec || sec <= 0) return null;
  const mins = Math.floor(sec / 60);
  const rem = sec % 60;
  return `${mins}:${rem.toString().padStart(2, "0")}`;
}

function clipsEqual(a: DemoClipRange | null, b: DemoClipRange | null): boolean {
  if (!a && !b) return true;
  if (!a || !b) return false;
  return a.startSec === b.startSec && a.endSec === b.endSec;
}

function buildInitialSelections(
  videos: AdminVideoItem[],
  initialDemoId: string,
  initialDemoClip: DemoClipRange | null,
): Record<string, string> {
  const map: Record<string, string> = {};
  for (const v of videos) {
    if (v.id === initialDemoId && initialDemoClip) {
      const matched = v.clips.find(
        (c) => c.startSec === initialDemoClip.startSec && c.endSec === initialDemoClip.endSec,
      );
      if (matched) {
        map[v.id] = matched.key;
        continue;
      }
    }
    if (needsCrop(v.durationSec)) {
      map[v.id] = v.clips[0]?.key ?? "";
    } else {
      map[v.id] = "full";
    }
  }
  return map;
}

export function AdminDemoPicker({
  videos,
  initialDemoId,
  initialDemoClip,
}: {
  videos: AdminVideoItem[];
  initialDemoId: string;
  initialDemoClip: DemoClipRange | null;
}) {
  const [activeId, setActiveId] = useState(initialDemoId);
  const [activeClip, setActiveClip] = useState<DemoClipRange | null>(initialDemoClip);
  const [selectedByVideo, setSelectedByVideo] = useState<Record<string, string>>(() =>
    buildInitialSelections(videos, initialDemoId, initialDemoClip),
  );
  const [pendingId, setPendingId] = useState<string | null>(null);
  const [isPending, startTransition] = useTransition();

  const resolveSelectedClip = (v: AdminVideoItem): DemoClipRange | null => {
    const key = selectedByVideo[v.id];
    if (!key || key === "full") return null;
    const found = v.clips.find((c) => c.key === key);
    return found ? { startSec: found.startSec, endSec: found.endSec } : null;
  };

  const handleSelect = (v: AdminVideoItem) => {
    const clip = resolveSelectedClip(v);
    setPendingId(v.id);
    startTransition(async () => {
      const res = await setDemoVideo(v.id, clip);
      setPendingId(null);
      if (!res.ok) {
        toast.error(res.error ?? "Failed to update demo video.");
        return;
      }
      setActiveId(v.id);
      setActiveClip(clip);
      toast.success(
        clip
          ? `Demo video updated (${formatTimestamp(clip.startSec)}–${formatTimestamp(clip.endSec)})!`
          : "Demo video updated!",
      );
    });
  };

  if (videos.length === 0) {
    return (
      <Card className="rounded-2xl border-dashed">
        <CardContent className="py-12 text-center text-sm text-muted-foreground">
          No videos uploaded yet. Paste a YouTube link on the dashboard first.
        </CardContent>
      </Card>
    );
  }

  return (
    <div className="grid gap-5 sm:grid-cols-2 lg:grid-cols-3">
      {videos.map((v) => {
        const longVideo = needsCrop(v.durationSec);
        const selectedClip = resolveSelectedClip(v);
        const isActiveVideo = v.id === activeId;
        const isExactActive = isActiveVideo && clipsEqual(selectedClip, activeClip);
        const isSavingThis = isPending && pendingId === v.id;
        const displayDur = selectedClip
          ? formatDuration(selectedClip.endSec - selectedClip.startSec)
          : formatDuration(v.durationSec);
        const needsClipFirst = longVideo && v.clips.length === 0;
        const showClipPicker = longVideo || v.clips.length > 0;

        return (
          <Card
            key={v.id}
            className={cn(
              "flex flex-col overflow-hidden rounded-2xl transition-all",
              isActiveVideo && "ring-2 ring-[#10B981]",
            )}
          >
            <div className="relative aspect-video w-full overflow-hidden bg-muted">
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img
                src={thumbnailUrl(v.id)}
                alt={v.title}
                className="size-full object-cover"
              />
              {displayDur && (
                <span className="absolute right-2 bottom-2 rounded-md bg-black/80 px-1.5 py-0.5 font-mono text-xs text-white">
                  {displayDur}
                </span>
              )}
              {selectedClip && (
                <span className="absolute bottom-2 left-2 flex items-center gap-1 rounded-md bg-black/80 px-1.5 py-0.5 font-mono text-[11px] text-emerald-300">
                  <Scissors className="size-3" />
                  {formatTimestamp(selectedClip.startSec)}–{formatTimestamp(selectedClip.endSec)}
                </span>
              )}
              {isActiveVideo && (
                <Badge className="absolute top-2 left-2 bg-[#10B981] text-[11px] font-semibold text-zinc-950">
                  <Sparkles className="mr-1 size-3" />
                  Active Demo
                </Badge>
              )}
              {v.isAutoGenerated && (
                <Badge
                  variant="secondary"
                  className="absolute top-2 right-2 bg-background/90 text-[11px] backdrop-blur"
                >
                  Auto captions
                </Badge>
              )}
            </div>

            <CardContent className="flex flex-1 flex-col justify-between gap-4 p-4">
              <div className="space-y-3">
                <div className="space-y-1">
                  <h3 className="line-clamp-2 text-sm font-semibold leading-snug">{v.title}</h3>
                  {v.channel && (
                    <p className="truncate text-xs text-muted-foreground">{v.channel}</p>
                  )}
                  <p className="font-mono text-[11px] text-muted-foreground/70">{v.id}</p>
                </div>

                {showClipPicker && (
                  <div className="space-y-1.5">
                    <label
                      htmlFor={`clip-select-${v.id}`}
                      className="flex items-center gap-1 text-[11px] font-medium text-muted-foreground"
                    >
                      <Scissors className="size-3 text-[#10B981]" />
                      Clip version for Demo
                    </label>
                    {needsClipFirst ? (
                      <p className="rounded-md border border-dashed px-2.5 py-2 text-xs text-muted-foreground">
                        Video &gt; 15 min has no cropped clip yet.{" "}
                        <Link
                          href={`/crop/${v.id}`}
                          className="font-medium text-[#10B981] hover:underline dark:text-[#34D399]"
                        >
                          Crop now
                        </Link>
                      </p>
                    ) : (
                      <select
                        id={`clip-select-${v.id}`}
                        value={selectedByVideo[v.id] ?? (longVideo ? "" : "full")}
                        onChange={(e) =>
                          setSelectedByVideo((prev) => ({ ...prev, [v.id]: e.target.value }))
                        }
                        disabled={isPending}
                        className="h-9 w-full rounded-md border border-input bg-background px-2.5 text-xs shadow-xs focus:border-[#10B981] focus:outline-none"
                      >
                        {!longVideo && (
                          <option value="full">
                            Full video ({formatDuration(v.durationSec) ?? "full"})
                          </option>
                        )}
                        {v.clips.map((c) => (
                          <option key={c.key} value={c.key}>
                            {c.label} ({formatTimestamp(c.startSec)}–{formatTimestamp(c.endSec)})
                          </option>
                        ))}
                      </select>
                    )}
                  </div>
                )}
              </div>

              <div className="flex items-center gap-2">
                <Button
                  type="button"
                  disabled={isExactActive || isPending || needsClipFirst}
                  onClick={() => handleSelect(v)}
                  className={cn(
                    "h-10 flex-1 rounded-md font-semibold",
                    isExactActive
                      ? "bg-[#10B981]/15 text-[#10B981] dark:text-[#34D399]"
                      : "bg-[#10B981] text-zinc-950 hover:bg-[#34D399]",
                  )}
                >
                  {isSavingThis ? (
                    <Loader2 className="size-4 animate-spin" />
                  ) : isExactActive ? (
                    <>
                      <CheckCircle2 className="size-4" />
                      Current Demo
                    </>
                  ) : isActiveVideo ? (
                    "Update Demo Clip"
                  ) : (
                    "Set as Demo"
                  )}
                </Button>

                <Button
                  asChild
                  variant="outline"
                  size="icon"
                  className="size-10 shrink-0 rounded-md"
                  title="Preview practice"
                >
                  <Link href={`/practice/${v.id}`}>
                    <Play className="size-4" />
                  </Link>
                </Button>
              </div>
            </CardContent>
          </Card>
        );
      })}
    </div>
  );
}
