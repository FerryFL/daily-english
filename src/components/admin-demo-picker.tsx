"use client";

import { useState, useTransition } from "react";
import { CheckCircle2, Loader2, Play, Sparkles } from "lucide-react";
import Link from "next/link";
import { toast } from "sonner";
import { setDemoVideo } from "@/app/admin/actions";
import { thumbnailUrl } from "@/lib/youtube";
import { cn } from "@/lib/utils";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";

export interface AdminVideoItem {
  id: string;
  title: string;
  channel: string | null;
  durationSec: number | null;
  isAutoGenerated: boolean;
}

function formatDuration(sec: number | null): string | null {
  if (!sec || sec <= 0) return null;
  const mins = Math.floor(sec / 60);
  const rem = sec % 60;
  return `${mins}:${rem.toString().padStart(2, "0")}`;
}

export function AdminDemoPicker({
  videos,
  initialDemoId,
}: {
  videos: AdminVideoItem[];
  initialDemoId: string;
}) {
  const [activeId, setActiveId] = useState(initialDemoId);
  const [pendingId, setPendingId] = useState<string | null>(null);
  const [isPending, startTransition] = useTransition();

  const handleSelect = (videoId: string) => {
    setPendingId(videoId);
    startTransition(async () => {
      const res = await setDemoVideo(videoId);
      setPendingId(null);
      if (!res.ok) {
        toast.error(res.error ?? "Failed to update demo video.");
        return;
      }
      setActiveId(videoId);
      toast.success("Demo video updated!");
    });
  };

  if (videos.length === 0) {
    return (
      <Card className="rounded-2xl border-dashed">
        <CardContent className="py-12 text-center text-sm text-muted-foreground">
          No videos uploaded yet. Paste a YouTube link on the dashboard first.
        </CardContent>
      </Card>
    );
  }

  return (
    <div className="grid gap-5 sm:grid-cols-2 lg:grid-cols-3">
      {videos.map((v) => {
        const isActive = v.id === activeId;
        const isSavingThis = isPending && pendingId === v.id;
        const dur = formatDuration(v.durationSec);

        return (
          <Card
            key={v.id}
            className={cn(
              "overflow-hidden rounded-2xl transition-all",
              isActive && "ring-2 ring-[#10B981]",
            )}
          >
            <div className="relative aspect-video w-full overflow-hidden bg-muted">
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img
                src={thumbnailUrl(v.id)}
                alt={v.title}
                className="size-full object-cover"
              />
              {dur && (
                <span className="absolute right-2 bottom-2 rounded-md bg-black/80 px-1.5 py-0.5 font-mono text-xs text-white">
                  {dur}
                </span>
              )}
              {isActive && (
                <Badge className="absolute top-2 left-2 bg-[#10B981] text-[11px] font-semibold text-zinc-950">
                  <Sparkles className="mr-1 size-3" />
                  Active Demo
                </Badge>
              )}
              {v.isAutoGenerated && (
                <Badge
                  variant="secondary"
                  className="absolute top-2 right-2 bg-background/90 text-[11px] backdrop-blur"
                >
                  Auto captions
                </Badge>
              )}
            </div>

            <CardContent className="space-y-4 p-4">
              <div className="space-y-1">
                <h3 className="line-clamp-2 text-sm font-semibold leading-snug">{v.title}</h3>
                {v.channel && (
                  <p className="truncate text-xs text-muted-foreground">{v.channel}</p>
                )}
                <p className="font-mono text-[11px] text-muted-foreground/70">{v.id}</p>
              </div>

              <div className="flex items-center gap-2">
                <Button
                  type="button"
                  disabled={isActive || isPending}
                  onClick={() => handleSelect(v.id)}
                  className={cn(
                    "h-10 flex-1 rounded-md font-semibold",
                    isActive
                      ? "bg-[#10B981]/15 text-[#10B981] dark:text-[#34D399]"
                      : "bg-[#10B981] text-zinc-950 hover:bg-[#34D399]",
                  )}
                >
                  {isSavingThis ? (
                    <Loader2 className="size-4 animate-spin" />
                  ) : isActive ? (
                    <>
                      <CheckCircle2 className="size-4" />
                      Current Demo
                    </>
                  ) : (
                    "Set as Demo"
                  )}
                </Button>

                <Button
                  asChild
                  variant="outline"
                  size="icon"
                  className="size-10 shrink-0 rounded-md"
                  title="Preview practice"
                >
                  <Link href={`/practice/${v.id}`}>
                    <Play className="size-4" />
                  </Link>
                </Button>
              </div>
            </CardContent>
          </Card>
        );
      })}
    </div>
  );
}
