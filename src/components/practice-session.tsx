"use client";

import { useCallback, useMemo, useRef, useState } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { ArrowLeft, Lock, Scissors } from "lucide-react";
import { toast } from "sonner";
import { resetVideoProgress, saveChunkResult } from "@/app/practice/actions";
import { makeBlanks, type BlankToken } from "@/lib/blanker";
import { check, isPassing } from "@/lib/checker";
import type { Chunk } from "@/lib/chunker";
import { formatTimestamp } from "@/lib/clip";
import { cn } from "@/lib/utils";
import { useShortcuts } from "@/hooks/use-shortcuts";
import { ChunkCard, type BlankStatus } from "@/components/chunk-card";
import { PracticeSummary, type CompletedChunkRecord } from "@/components/practice-summary";
import { ThemeToggle } from "@/components/theme-toggle";
import { YouTubePlayer, type YouTubePlayerHandle } from "@/components/youtube-player";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Progress } from "@/components/ui/progress";

interface PracticeSessionProps {
  videoId: string;
  title: string;
  isAutoGenerated: boolean;
  chunks: Chunk[];
  initialChunkIndex: number;
  initialCompleted: boolean;
  initialRecords: CompletedChunkRecord[];
  isDemo?: boolean;
  clipRange?: { startSec: number; endSec: number } | null;
}

export function PracticeSession({
  videoId,
  title,
  isAutoGenerated,
  chunks,
  initialChunkIndex,
  initialCompleted,
  initialRecords,
  isDemo = false,
  clipRange = null,
}: PracticeSessionProps) {
  const router = useRouter();
  const playerRef = useRef<YouTubePlayerHandle | null>(null);

  const clampedInitial = Math.min(
    Math.max(0, initialChunkIndex),
    Math.max(0, chunks.length - 1),
  );
  const [chunkIndex, setChunkIndex] = useState(clampedInitial);
  const [maxUnlockedChunk, setMaxUnlockedChunk] = useState(
    initialCompleted ? Math.max(0, chunks.length - 1) : clampedInitial,
  );
  const [hasCompleted, setHasCompleted] = useState(initialCompleted);
  const [showSummary, setShowSummary] = useState(initialCompleted && chunks.length > 0);
  const [records, setRecords] = useState<CompletedChunkRecord[]>(initialRecords);

  const [values, setValues] = useState<Record<number, string>>({});
  const [statuses, setStatuses] = useState<Record<number, BlankStatus>>({});
  const [missedSet, setMissedSet] = useState<Set<string>>(() => new Set());
  const [attempts, setAttempts] = useState(0);
  const [rate, setRate] = useState(1);

  const chunk = chunks[chunkIndex];
  const tokens = useMemo(
    () => (chunk ? makeBlanks(chunk.text, `${videoId}:${chunk.index}`) : []),
    [chunk, videoId],
  );
  const blanks = useMemo(
    () => tokens.filter((t): t is BlankToken => t.kind === "blank"),
    [tokens],
  );

  const unlocked = useMemo(() => {
    if (blanks.length === 0) return true;
    return blanks.every((b) => {
      const s = statuses[b.id];
      return isPassing(s === "idle" ? undefined : s);
    });
  }, [blanks, statuses]);

  const playChunk = useCallback(
    (idx: number, loop = true) => {
      const target = chunks[idx];
      if (!target) return;
      playerRef.current?.playSegment(target.start, target.end, loop);
    },
    [chunks],
  );

  const handleRepeat = useCallback(() => {
    playChunk(chunkIndex);
  }, [chunkIndex, playChunk]);

  const handleRateChange = useCallback((nextRate: number) => {
    setRate(nextRate);
    playerRef.current?.setRate(nextRate);
  }, []);

  const handleValueChange = useCallback((blankId: number, val: string) => {
    setValues((prev) => ({ ...prev, [blankId]: val }));
    // Clear wrong highlight as soon as user starts editing again.
    setStatuses((prev) => (prev[blankId] === "wrong" ? { ...prev, [blankId]: "idle" } : prev));
  }, []);

  const handleCheck = useCallback(() => {
    if (unlocked || !chunk) return;

    const nextStatuses: Record<number, BlankStatus> = { ...statuses };
    const nextMissed = new Set(missedSet);

    for (const b of blanks) {
      const current = statuses[b.id];
      if (current === "correct" || current === "almost" || current === "revealed") continue;
      const res = check(values[b.id] ?? "", b.answer);
      nextStatuses[b.id] = res;
      if (res === "wrong") nextMissed.add(b.answer);
    }

    setStatuses(nextStatuses);
    setMissedSet(nextMissed);
    setAttempts((a) => a + 1);
  }, [blanks, chunk, missedSet, statuses, unlocked, values]);

  const handleReveal = useCallback(() => {
    if (unlocked || !chunk) return;

    const nextStatuses: Record<number, BlankStatus> = { ...statuses };
    const nextMissed = new Set(missedSet);

    for (const b of blanks) {
      const current = statuses[b.id];
      if (current === "correct" || current === "almost" || current === "revealed") continue;
      nextStatuses[b.id] = "revealed";
      nextMissed.add(b.answer);
    }

    setStatuses(nextStatuses);
    setMissedSet(nextMissed);
  }, [blanks, chunk, missedSet, statuses, unlocked]);

  const handleSelectChunk = useCallback(
    (idx: number) => {
      if (idx < 0 || idx > maxUnlockedChunk || idx >= chunks.length) return;
      setShowSummary(false);
      setChunkIndex(idx);
      setValues({});
      setStatuses({});
      setMissedSet(new Set());
      setAttempts(0);
      playChunk(idx, true);
    },
    [chunks.length, maxUnlockedChunk, playChunk],
  );

  const handleNext = useCallback(() => {
    if (!unlocked || !chunk) return;

    const isReviewingOldChunk = hasCompleted || chunkIndex < maxUnlockedChunk;
    const isLastChunk = chunkIndex >= chunks.length - 1;

    if (isDemo) {
      if (isLastChunk) {
        playerRef.current?.pause();
        toast.success("Demo finished! Sign in to practice with your own YouTube videos.");
        router.push("/");
        return;
      }

      setMaxUnlockedChunk((prev) => Math.max(prev, chunkIndex + 1));
      const nextIdx = chunkIndex + 1;
      setChunkIndex(nextIdx);
      setValues({});
      setStatuses({});
      setMissedSet(new Set());
      setAttempts(0);
      playChunk(nextIdx, true);
      return;
    }

    if (!isReviewingOldChunk) {
      const blanksTotal = blanks.length;
      const revealedCount = blanks.filter((b) => statuses[b.id] === "revealed").length;
      const blanksCorrect = blanks.filter(
        (b) => statuses[b.id] === "correct" || statuses[b.id] === "almost",
      ).length;
      const missedWords = Array.from(missedSet);

      const record: CompletedChunkRecord = {
        chunkIndex: chunk.index,
        blanksTotal,
        blanksCorrect,
        revealedCount,
        missedWords,
      };

      setRecords((prev) => [...prev.filter((r) => r.chunkIndex !== chunk.index), record]);

      if (isLastChunk) {
        setHasCompleted(true);
      } else {
        setMaxUnlockedChunk((prev) => Math.max(prev, chunkIndex + 1));
      }

      // Persist in background so transitions feel instant.
      void saveChunkResult({
        videoId,
        chunkIndex: chunk.index,
        totalChunks: chunks.length,
        blanksTotal,
        blanksCorrect,
        revealedCount,
        attempts: Math.max(1, attempts),
        missedWords,
        isLastChunk,
      }).catch(() => {
        toast.error("Could not save progress to database.");
      });
    }

    if (isLastChunk) {
      playerRef.current?.pause();
      setShowSummary(true);
      return;
    }

    const nextIdx = chunkIndex + 1;
    setChunkIndex(nextIdx);
    setValues({});
    setStatuses({});
    setMissedSet(new Set());
    setAttempts(0);
    playChunk(nextIdx, true);
  }, [
    attempts,
    blanks,
    chunk,
    chunkIndex,
    chunks.length,
    hasCompleted,
    isDemo,
    maxUnlockedChunk,
    missedSet,
    playChunk,
    router,
    statuses,
    unlocked,
    videoId,
  ]);

  const handlePracticeAgain = useCallback(() => {
    setShowSummary(false);
    setHasCompleted(false);
    setMaxUnlockedChunk(0);
    setChunkIndex(0);
    setValues({});
    setStatuses({});
    setMissedSet(new Set());
    setAttempts(0);
    setRecords([]);
    void resetVideoProgress(videoId, chunks.length);
    playChunk(0, true);
  }, [chunks.length, playChunk, videoId]);

  useShortcuts({
    enabled: !showSummary && Boolean(chunk),
    onRepeat: handleRepeat,
    onReveal: handleReveal,
    onSubmitOrNext: () => {
      if (unlocked) handleNext();
      else handleCheck();
    },
  });

  const progressPct =
    chunks.length > 0
      ? hasCompleted || showSummary
        ? 100
        : Math.round(
            ((maxUnlockedChunk + (chunkIndex === maxUnlockedChunk && unlocked ? 1 : 0)) /
              chunks.length) *
              100,
          )
      : 0;

  return (
    <div className="flex min-h-svh flex-col bg-background">
      {/* Slim top bar */}
      <header className="sticky top-0 z-30 border-b bg-background/85 backdrop-blur">
        <div className="mx-auto flex h-14 max-w-4xl items-center justify-between gap-3 px-4">
          <Button asChild variant="ghost" size="sm" className="shrink-0">
            <Link href="/">
              <ArrowLeft className="size-4" />
              <span>Dashboard</span>
            </Link>
          </Button>

          <ThemeToggle />
        </div>
      </header>

      <main className="mx-auto w-full max-w-4xl flex-1 space-y-5 px-4 py-6 sm:px-6 sm:py-8">
        <YouTubePlayer
          ref={playerRef}
          videoId={videoId}
          onReady={() => {
            if (!showSummary && chunk) playChunk(chunkIndex, true);
          }}
        />

        {/* Video title, part progress & progress bar below video */}
        <div className="space-y-2">
          <div className="flex flex-wrap items-center justify-between gap-2">
            <div className="flex min-w-0 items-center gap-2">
              <h1 className="truncate text-base font-semibold tracking-tight text-foreground sm:text-lg">
                {title}
              </h1>
              {isDemo && (
                <Badge className="shrink-0 bg-[#10B981] text-[11px] font-semibold text-zinc-950">
                  Demo
                </Badge>
              )}
              {isAutoGenerated && (
                <Badge variant="secondary" className="shrink-0 text-[11px]">
                  Auto captions
                </Badge>
              )}
              {clipRange && !isDemo && (
                <Link href={`/crop/${videoId}`} className="shrink-0">
                  <Badge
                    variant="outline"
                    className="gap-1 font-mono text-[11px] hover:border-[#10B981] hover:text-[#10B981]"
                    title="Change cropped range"
                  >
                    <Scissors className="size-3" />
                    {formatTimestamp(clipRange.startSec)}–{formatTimestamp(clipRange.endSec)}
                  </Badge>
                </Link>
              )}
            </div>
            <span className="shrink-0 font-mono text-xs text-[#10B981] dark:text-[#34D399]">
              {showSummary ? "Complete" : `Part ${chunkIndex + 1} / ${chunks.length}`}
            </span>
          </div>
          <Progress value={progressPct} className="h-1.5" />

          {!showSummary && chunks.length > 0 && (
            <div className="flex items-center gap-1.5 overflow-x-auto pt-1 pb-3">
              {chunks.map((c) => {
                const isCurrent = c.index === chunkIndex;
                const isUnlockedItem = c.index <= maxUnlockedChunk;
                return (
                  <button
                    key={c.index}
                    type="button"
                    disabled={!isUnlockedItem}
                    onClick={() => handleSelectChunk(c.index)}
                    title={
                      isUnlockedItem
                        ? `Go to Part ${c.index + 1}`
                        : `Complete Part ${maxUnlockedChunk + 1} to unlock`
                    }
                    className={cn(
                      "inline-flex h-8 shrink-0 items-center gap-1 rounded-md border px-2.5 font-mono text-xs font-medium transition-colors",
                      isCurrent &&
                        "border-[#10B981] bg-[#10B981] font-semibold text-zinc-950",
                      !isCurrent &&
                        isUnlockedItem &&
                        "border-[#10B981]/30 bg-[#10B981]/10 text-[#10B981] hover:bg-[#10B981]/20 dark:text-[#34D399]",
                      !isUnlockedItem &&
                        "cursor-not-allowed border-border/60 bg-muted/40 text-muted-foreground/50",
                    )}
                  >
                    {!isUnlockedItem && <Lock className="size-3" />}
                    {c.index + 1}
                  </button>
                );
              })}
            </div>
          )}
        </div>

        {showSummary ? (
          <PracticeSummary
            videoId={videoId}
            title={title}
            chunks={chunks}
            records={records}
            onReplayChunk={(idx) => playChunk(idx, false)}
            onPracticeAgain={handlePracticeAgain}
          />
        ) : chunk ? (
          <ChunkCard
            chunkIndex={chunk.index}
            start={chunk.start}
            end={chunk.end}
            tokens={tokens}
            values={values}
            statuses={statuses}
            attempts={attempts}
            unlocked={unlocked}
            isLastChunk={chunkIndex >= chunks.length - 1}
            isDemo={isDemo}
            rate={rate}
            onValueChange={handleValueChange}
            onRateChange={handleRateChange}
            onRepeat={handleRepeat}
            onCheck={handleCheck}
            onReveal={handleReveal}
            onNext={handleNext}
          />
        ) : null}
      </main>
    </div>
  );
}
