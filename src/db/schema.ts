import { sql } from "drizzle-orm";
import {
  boolean,
  index,
  integer,
  jsonb,
  pgPolicy,
  pgTable,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";
import { anonRole, authenticatedRole, authUsers } from "drizzle-orm/supabase";
import type { Segment } from "@/lib/chunker";

/** Cached YouTube transcripts, shared across all users. */
export const videos = pgTable(
  "english_videos",
  {
    id: text("id").primaryKey(), // YouTube video id
    title: text("title").notNull(),
    channel: text("channel"),
    durationSec: integer("duration_sec"),
    isAutoGenerated: boolean("is_auto_generated").notNull().default(false),
    segments: jsonb("segments").$type<Segment[]>().notNull(),
    fetchedAt: timestamp("fetched_at", { withTimezone: true }).notNull().defaultNow(),
  },
  () => [
    pgPolicy("english_videos_read_authenticated", {
      for: "select",
      to: authenticatedRole,
      using: sql`true`,
    }),
  ],
).enableRLS();

/** Where each user is in each video. */
export const progress = pgTable(
  "english_progress",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: uuid("user_id")
      .notNull()
      .references(() => authUsers.id, { onDelete: "cascade" }),
    videoId: text("video_id")
      .notNull()
      .references(() => videos.id, { onDelete: "cascade" }),
    currentChunk: integer("current_chunk").notNull().default(0),
    totalChunks: integer("total_chunks").notNull(),
    completed: boolean("completed").notNull().default(false),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    uniqueIndex("english_progress_user_video_idx").on(t.userId, t.videoId),
    pgPolicy("english_progress_own_rows", {
      for: "all",
      to: authenticatedRole,
      using: sql`${t.userId} = (select auth.uid())`,
      withCheck: sql`${t.userId} = (select auth.uid())`,
    }),
  ],
).enableRLS();

/** One row per finished chunk (checked correct or revealed). */
export const chunkAttempts = pgTable(
  "english_chunk_attempts",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: uuid("user_id")
      .notNull()
      .references(() => authUsers.id, { onDelete: "cascade" }),
    videoId: text("video_id")
      .notNull()
      .references(() => videos.id, { onDelete: "cascade" }),
    chunkIndex: integer("chunk_index").notNull(),
    blanksTotal: integer("blanks_total").notNull(),
    blanksCorrect: integer("blanks_correct").notNull(),
    revealedCount: integer("revealed_count").notNull().default(0),
    attempts: integer("attempts").notNull().default(1),
    missedWords: text("missed_words").array().notNull().default(sql`'{}'::text[]`),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    index("english_attempts_user_video_idx").on(t.userId, t.videoId),
    pgPolicy("english_attempts_own_rows", {
      for: "all",
      to: authenticatedRole,
      using: sql`${t.userId} = (select auth.uid())`,
      withCheck: sql`${t.userId} = (select auth.uid())`,
    }),
  ],
).enableRLS();

/** App-level key/value settings (e.g. `demo_video_id`). */
export const settings = pgTable(
  "english_settings",
  {
    key: text("key").primaryKey(),
    value: text("value").notNull(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  () => [
    pgPolicy("english_settings_read_public", {
      for: "select",
      to: [anonRole, authenticatedRole],
      using: sql`true`,
    }),
  ],
).enableRLS();

export type Video = typeof videos.$inferSelect;
export type Progress = typeof progress.$inferSelect;
export type ChunkAttempt = typeof chunkAttempts.$inferSelect;
export type Setting = typeof settings.$inferSelect;
