import "server-only";
import type { Segment } from "./chunker";

export interface TranscriptResult {
  videoId: string;
  title: string;
  channel: string | null;
  durationSec: number | null;
  isAutoGenerated: boolean;
  segments: Segment[];
}

export const MAX_VIDEO_DURATION_SEC = 15 * 60; // 15 minutes

export class TranscriptError extends Error {
  constructor(
    message: string,
    public status: 400 | 404 | 502,
  ) {
    super(message);
  }
}

interface CaptionTrack {
  baseUrl?: string;
  languageCode?: string;
  kind?: string;
}

interface PlayerResponse {
  playabilityStatus?: { status?: string; reason?: string };
  videoDetails?: {
    title?: string;
    author?: string;
    lengthSeconds?: string;
  };
  captions?: {
    playerCaptionsTracklistRenderer?: {
      captionTracks?: CaptionTrack[];
    };
  };
}

/** Parse YouTube timedtext XML (`<text start="..." dur="...">` or `<p t="..." d="...">`). */
export function parseTimedTextXml(xml: string): Segment[] {
  const segments: Segment[] = [];

  // Standard timedtext format: <text start="1.57" dur="4.36">...</text>
  const textRe = /<text\b([^>]*)>([\s\S]*?)<\/text>/g;
  let match: RegExpExecArray | null;
  while ((match = textRe.exec(xml)) !== null) {
    const attrs = match[1];
    const startMatch = attrs.match(/\bstart="([^"]+)"/);
    const durMatch = attrs.match(/\bdur="([^"]+)"/);
    const start = Number(startMatch?.[1] ?? 0);
    const dur = Number(durMatch?.[1] ?? 0);
    const text = match[2].replace(/<[^>]+>/g, "").trim();
    if (!Number.isNaN(start) && text) {
      segments.push({ start, dur: Number.isNaN(dur) ? 0 : dur, text });
    }
  }
  if (segments.length > 0) return segments;

  // Fallback srv3 format: <p t="1570" d="4360">...</p>
  const pRe = /<p\b([^>]*)>([\s\S]*?)<\/p>/g;
  while ((match = pRe.exec(xml)) !== null) {
    const attrs = match[1];
    const tMatch = attrs.match(/\bt="([^"]+)"/);
    const dMatch = attrs.match(/\bd="([^"]+)"/);
    if (!tMatch) continue;
    const start = Number(tMatch[1]) / 1000;
    const dur = Number(dMatch?.[1] ?? 0) / 1000;
    const text = match[2].replace(/<[^>]+>/g, "").trim();
    if (!Number.isNaN(start) && text) {
      segments.push({ start, dur: Number.isNaN(dur) ? 0 : dur, text });
    }
  }

  return segments;
}

const HEADERS = {
  "Accept-Language": "en-US,en;q=0.9",
  "User-Agent":
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/134.0.0.0 Safari/537.36",
};

async function fetchInnertubeApiKey(videoId: string): Promise<string> {
  const res = await fetch(`https://www.youtube.com/watch?v=${videoId}`, {
    headers: HEADERS,
    cache: "no-store",
  });
  if (!res.ok) {
    throw new TranscriptError("Could not reach YouTube. Please try again.", 502);
  }
  const html = await res.text();
  const apiKey = html.match(/"INNERTUBE_API_KEY":"([^"]+)"/)?.[1];
  if (!apiKey) {
    throw new TranscriptError("Could not initialize YouTube client. Please try again.", 502);
  }
  return apiKey;
}

async function fetchAndroidPlayer(videoId: string, apiKey: string): Promise<PlayerResponse> {
  const res = await fetch(`https://www.youtube.com/youtubei/v1/player?key=${apiKey}`, {
    method: "POST",
    headers: { "Content-Type": "application/json", "Accept-Language": "en-US,en;q=0.9" },
    body: JSON.stringify({
      context: {
        client: {
          clientName: "ANDROID",
          clientVersion: "20.10.38",
          hl: "en",
          gl: "US",
        },
      },
      videoId,
    }),
    cache: "no-store",
  });
  if (!res.ok) {
    throw new TranscriptError("Could not reach YouTube player API. Please try again.", 502);
  }
  return (await res.json()) as PlayerResponse;
}

async function fetchTrackXml(baseUrl: string): Promise<Segment[]> {
  // Strip `&fmt=srv3` so YouTube returns standard XML without PoToken blocking.
  const cleanUrl = baseUrl.replace(/&fmt=[^&]+/g, "");
  for (const url of [cleanUrl, baseUrl]) {
    const res = await fetch(url, {
      headers: { "Accept-Language": "en-US,en;q=0.9" },
      cache: "no-store",
    });
    if (!res.ok) continue;
    const xml = await res.text();
    if (!xml.trim()) continue;
    const segments = parseTimedTextXml(xml);
    if (segments.length > 0) return segments;
  }
  return [];
}

export async function fetchTranscript(videoId: string): Promise<TranscriptResult> {
  let data: PlayerResponse;
  try {
    const apiKey = await fetchInnertubeApiKey(videoId);
    data = await fetchAndroidPlayer(videoId, apiKey);
  } catch (e) {
    if (e instanceof TranscriptError) throw e;
    console.error("[transcript] player fetch failed", e);
    throw new TranscriptError("Could not reach YouTube. Please try again.", 502);
  }

  if (data.playabilityStatus?.status && data.playabilityStatus.status !== "OK") {
    throw new TranscriptError(
      data.playabilityStatus.reason || "This video is unavailable.",
      404,
    );
  }

  const title = data.videoDetails?.title ?? "Untitled video";
  const channel = data.videoDetails?.author ?? null;
  const parsedDuration = Number(data.videoDetails?.lengthSeconds);
  const durationSec = Number.isFinite(parsedDuration) && parsedDuration > 0 ? parsedDuration : null;

  if (durationSec !== null && durationSec > MAX_VIDEO_DURATION_SEC) {
    throw new TranscriptError(
      "This video is longer than 15 minutes. Please choose a shorter video (max 15 minutes).",
      400,
    );
  }

  const allTracks = data.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
  const englishTracks = allTracks.filter((t) =>
    (t.languageCode ?? "").toLowerCase().startsWith("en"),
  );

  if (englishTracks.length === 0) {
    throw new TranscriptError("This video has no English captions.", 404);
  }

  // Prefer manually-created English captions first, then auto-generated (asr).
  const ordered = [
    ...englishTracks.filter((t) => t.kind !== "asr"),
    ...englishTracks.filter((t) => t.kind === "asr"),
  ];

  for (const track of ordered) {
    if (!track.baseUrl) continue;
    const segments = await fetchTrackXml(track.baseUrl).catch(() => []);
    if (segments.length > 0) {
      return {
        videoId,
        title,
        channel,
        durationSec,
        isAutoGenerated: track.kind === "asr",
        segments,
      };
    }
  }

  throw new TranscriptError(
    "Captions exist but YouTube refused to send them. Please try again later.",
    502,
  );
}
