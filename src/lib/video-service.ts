import "server-only";
import { eq, inArray } from "drizzle-orm";
import { getDb, isDbConfigured } from "@/db";
import { progress, settings, videos, type Video } from "@/db/schema";
import { MAX_VIDEO_DURATION_SEC } from "./clip";
import { DEFAULT_DEMO_VIDEO } from "./demo";
import { fetchTranscript } from "./transcript";

export const DEMO_SETTING_KEY = "demo_video_id";
export const DEMO_CLIP_SETTING_KEY = "demo_video_clip";

/**
 * Look up a cached video transcript in `english_videos`.
 * On cache miss, fetch from YouTube and persist it for future requests.
 */
export async function getOrFetchVideo(videoId: string): Promise<Video> {
  if (isDbConfigured()) {
    const db = getDb();
    const [existing] = await db
      .select()
      .from(videos)
      .where(eq(videos.id, videoId))
      .limit(1);
    if (existing) {
      return existing;
    }
  }

  const fetched = await fetchTranscript(videoId);
  const record = {
    id: fetched.videoId,
    title: fetched.title,
    channel: fetched.channel,
    durationSec: fetched.durationSec,
    isAutoGenerated: fetched.isAutoGenerated,
    segments: fetched.segments,
  };

  if (isDbConfigured()) {
    const db = getDb();
    await db.insert(videos).values(record).onConflictDoNothing();
  }

  return { ...record, fetchedAt: new Date() };
}

/**
 * Ensure a `english_progress` row exists as soon as a user opens/uploads a video,
 * so it immediately appears on the Dashboard even at 0% (chunk 1).
 */
export async function ensureInitialProgress(
  userId: string,
  videoId: string,
  totalChunks: number,
): Promise<void> {
  if (!isDbConfigured() || totalChunks <= 0) return;
  const db = getDb();
  await db
    .insert(progress)
    .values({
      userId,
      videoId,
      currentChunk: 0,
      totalChunks,
      completed: false,
      updatedAt: new Date(),
    })
    .onConflictDoNothing({ target: [progress.userId, progress.videoId] });
}

export interface DemoVideoInfo {
  id: string;
  title: string;
  channel: string | null;
  durationSec: number | null;
  clipStartSec: number | null;
  clipEndSec: number | null;
}

function parseDemoClip(raw: string | undefined): { startSec: number; endSec: number } | null {
  if (!raw) return null;
  try {
    const parsed = JSON.parse(raw) as { startSec?: unknown; endSec?: unknown };
    const startSec = Number(parsed.startSec);
    const endSec = Number(parsed.endSec);
    if (
      Number.isFinite(startSec) &&
      Number.isFinite(endSec) &&
      startSec >= 0 &&
      endSec > startSec &&
      endSec - startSec <= MAX_VIDEO_DURATION_SEC
    ) {
      return { startSec: Math.round(startSec), endSec: Math.round(endSec) };
    }
  } catch {
    // ignore malformed setting
  }
  return null;
}

/**
 * Returns the currently configured demo video from `english_settings` + `english_videos`,
 * falling back to `DEFAULT_DEMO_VIDEO` (`w6199XN1Gyk`).
 */
export async function getActiveDemoVideo(): Promise<DemoVideoInfo> {
  let targetId = DEFAULT_DEMO_VIDEO.id;
  let clipStartSec: number | null = null;
  let clipEndSec: number | null = null;

  if (isDbConfigured()) {
    const db = getDb();
    const settingRows = await db
      .select()
      .from(settings)
      .where(inArray(settings.key, [DEMO_SETTING_KEY, DEMO_CLIP_SETTING_KEY]));

    const map = new Map(settingRows.map((r) => [r.key, r.value]));
    const configuredId = map.get(DEMO_SETTING_KEY);
    if (configuredId) targetId = configuredId;

    const clip = parseDemoClip(map.get(DEMO_CLIP_SETTING_KEY));
    if (clip) {
      clipStartSec = clip.startSec;
      clipEndSec = clip.endSec;
    }

    const [vid] = await db
      .select({
        id: videos.id,
        title: videos.title,
        channel: videos.channel,
        durationSec: videos.durationSec,
      })
      .from(videos)
      .where(eq(videos.id, targetId))
      .limit(1);

    if (vid) return { ...vid, clipStartSec, clipEndSec };
  }

  // If the default demo video hasn't been cached yet, fetch & cache it once so metadata is accurate.
  try {
    const fetched = await getOrFetchVideo(targetId);
    return {
      id: fetched.id,
      title: fetched.title,
      channel: fetched.channel,
      durationSec: fetched.durationSec,
      clipStartSec,
      clipEndSec,
    };
  } catch {
    return {
      id: targetId,
      title: DEFAULT_DEMO_VIDEO.title,
      channel: DEFAULT_DEMO_VIDEO.channel,
      durationSec: DEFAULT_DEMO_VIDEO.durationSec,
      clipStartSec,
      clipEndSec,
    };
  }
}
