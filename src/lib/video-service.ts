import "server-only";
import { eq } from "drizzle-orm";
import { getDb, isDbConfigured } from "@/db";
import { progress, settings, videos, type Video } from "@/db/schema";
import { DEFAULT_DEMO_VIDEO } from "./demo";
import {
  fetchTranscript,
  MAX_VIDEO_DURATION_SEC,
  TranscriptError,
} from "./transcript";

export const DEMO_SETTING_KEY = "demo_video_id";

/**
 * Look up a cached video transcript in `english_videos`.
 * On cache miss, fetch from YouTube and persist it for future requests.
 */
export async function getOrFetchVideo(videoId: string): Promise<Video> {
  if (isDbConfigured()) {
    const db = getDb();
    const [existing] = await db
      .select()
      .from(videos)
      .where(eq(videos.id, videoId))
      .limit(1);
    if (existing) {
      if (existing.durationSec !== null && existing.durationSec > MAX_VIDEO_DURATION_SEC) {
        throw new TranscriptError(
          "This video is longer than 15 minutes. Please choose a shorter video (max 15 minutes).",
          400,
        );
      }
      return existing;
    }
  }

  const fetched = await fetchTranscript(videoId);
  const record = {
    id: fetched.videoId,
    title: fetched.title,
    channel: fetched.channel,
    durationSec: fetched.durationSec,
    isAutoGenerated: fetched.isAutoGenerated,
    segments: fetched.segments,
  };

  if (isDbConfigured()) {
    const db = getDb();
    await db.insert(videos).values(record).onConflictDoNothing();
  }

  return { ...record, fetchedAt: new Date() };
}

/**
 * Ensure a `english_progress` row exists as soon as a user opens/uploads a video,
 * so it immediately appears on the Dashboard even at 0% (chunk 1).
 */
export async function ensureInitialProgress(
  userId: string,
  videoId: string,
  totalChunks: number,
): Promise<void> {
  if (!isDbConfigured() || totalChunks <= 0) return;
  const db = getDb();
  await db
    .insert(progress)
    .values({
      userId,
      videoId,
      currentChunk: 0,
      totalChunks,
      completed: false,
      updatedAt: new Date(),
    })
    .onConflictDoNothing({ target: [progress.userId, progress.videoId] });
}

export interface DemoVideoInfo {
  id: string;
  title: string;
  channel: string | null;
  durationSec: number | null;
}

/**
 * Returns the currently configured demo video from `english_settings` + `english_videos`,
 * falling back to `DEFAULT_DEMO_VIDEO` (`w6199XN1Gyk`).
 */
export async function getActiveDemoVideo(): Promise<DemoVideoInfo> {
  let targetId = DEFAULT_DEMO_VIDEO.id;

  if (isDbConfigured()) {
    const db = getDb();
    const [row] = await db
      .select()
      .from(settings)
      .where(eq(settings.key, DEMO_SETTING_KEY))
      .limit(1);
    if (row?.value) targetId = row.value;

    const [vid] = await db
      .select({
        id: videos.id,
        title: videos.title,
        channel: videos.channel,
        durationSec: videos.durationSec,
      })
      .from(videos)
      .where(eq(videos.id, targetId))
      .limit(1);

    if (vid) return vid;
  }

  // If the default demo video hasn't been cached yet, fetch & cache it once so metadata is accurate.
  try {
    const fetched = await getOrFetchVideo(targetId);
    return {
      id: fetched.id,
      title: fetched.title,
      channel: fetched.channel,
      durationSec: fetched.durationSec,
    };
  } catch {
    return {
      id: targetId,
      title: DEFAULT_DEMO_VIDEO.title,
      channel: DEFAULT_DEMO_VIDEO.channel,
      durationSec: DEFAULT_DEMO_VIDEO.durationSec,
    };
  }
}
